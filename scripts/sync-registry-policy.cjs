// Snapshot the registry's pure, non-executing source validators. No AWS dependencies.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ts = require('registry-typescript');
const root = path.resolve(__dirname, '..');
const registry = path.resolve(process.argv.find(arg => arg.startsWith('--registry='))?.slice(11) || path.join(root, '../fdo-plugins-aws-infra'));
const target = path.join(root, 'src/utils/plugins/publishing/registryPolicy');
const scanner = 'src/contexts/release-processing/infrastructure/scanners/';
const files = ['archive-common', 'archive-path', 'fdo-metadata', 'fdo-capabilities', 'fdo-source-package', 'source-archive', 'release-archive', 'typescript-security'].map(name => [name, scanner + name + '.ts']);
files.push(['plugin-id', 'src/contexts/catalog/domain/plugin-id.ts']);
files.push(['embedded-plugin-signature', 'src/contexts/identity/infrastructure/embedded-plugin-signature.ts']);
const provenance = {};
const check = process.argv.includes('--check');
fs.mkdirSync(target, {recursive: true});
for (const [name, relative] of files) {
    const original = fs.readFileSync(path.join(registry, relative), 'utf8');
    // Desktop trust verification uses pinned registryTrust, not the server's forge verifier.
    const source = name === 'embedded-plugin-signature'
        ? original.split('// Certificates are resolved')[0].replace(/^import .*from 'node-forge';\n/m, '').replace(/^import .*stable-stringify';\n/m, '')
        : original;
    provenance[relative] = crypto.createHash('sha256').update(original).digest('hex');
    const js = ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext}}).outputText
        .replace(/from '\.\.\/\.\.\/\.\.\/catalog\/domain\/plugin-id'/g, "from './plugin-id'");
    const adjusted = js.replace(/from '\.\.\/\.\.\/\.\.\/identity\/infrastructure\/embedded-plugin-signature'/g, "from './embedded-plugin-signature'").replace(/from '\.\.\/\.\.\/release-processing\/infrastructure\/scanners\/archive-common'/g, "from './archive-common'").replace(/from '\.\.\/\.\.\/\.\.\/shared\/serialization\/stable-stringify'/g, "from './stable-stringify'").replace(/from 'typescript'/g, "from 'registry-typescript'");
    const output = '// Generated by scripts/sync-registry-policy.cjs; edit the registry source, then sync.\n' + adjusted;
    const destination = path.join(target, name + '.js');
    if (check) {if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Registry policy drift: ' + relative);}
    else fs.writeFileSync(destination, output);
}
const manifest = JSON.stringify({source: 'fdo-plugins-aws-infra', files: provenance}, null, 2) + '\n';
const manifestPath = path.join(target, 'provenance.json');
if (check) {if (fs.readFileSync(manifestPath, 'utf8') !== manifest) throw new Error('Registry policy provenance drift.');}
else fs.writeFileSync(manifestPath, manifest);
console.log(check ? 'Registry policy matches.' : 'Registry policy synchronized.');
