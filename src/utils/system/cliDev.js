import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {getIgnoreInstance} from '../filesystem/getIgnoreInstance';
import {getAllFilesWithIgnorance} from '../filesystem/getAllFilesWithIgnorance';
import {pluginBuildEntrypoint} from '../plugins/runtime/pluginBuildArtifact';
import {requirePluginDirectory} from './cliPluginOperations';

// Polling avoids OS-specific recursive watcher limits and catches atomic editor saves.
export async function snapshotPluginWorkspace(directory, generated = new Set()) {
    const ignore = await getIgnoreInstance(directory, []);
    ignore.add(['node_modules/', '.git/']);
    const paths = await getAllFilesWithIgnorance(directory, relative => !ignore.ignores(relative.replace(/\\/g, '/')));
    const files = new Map();
    for (const file of paths.sort()) {
        const relative = path.relative(directory, file).replace(/\\/g, '/');
        if (generated.has(relative) || ['fdo.signature', 'fdo.meta.json'].includes(relative)) continue;
        const content = await fs.readFile(file);
        if (relative === '.fdoignore' && content.toString().startsWith('# .fdoignore autogenerated by FDO')) continue;
        files.set(relative, content);
    }
    // The compiler always reads package.json, even when an ignore rule hides it.
    try {files.set('package.json', await fs.readFile(path.join(directory, 'package.json')));}
    catch (error) {if (error.code !== 'ENOENT') throw error;}
    // Exclude the prospective output even before the first build. Malformed
    // manifests still enter the snapshot so fixing them triggers another build.
    const virtual = Object.fromEntries([...files].map(([name, content]) => ['/' + name, content.toString()]));
    try {files.delete(pluginBuildEntrypoint(virtual));} catch { /* Build reports manifest errors. */ }
    const hash = createHash('sha256');
    for (const [name, content] of files) {
        hash.update(JSON.stringify([name, content.length])); hash.update(content);
    }
    return hash.digest('hex');
}

export async function watchPluginDirectory(directory, {deploy, output = console, signals = process, pollInterval = 500, debounceMs = 250,
    snapshot = snapshotPluginWorkspace, now = Date.now, wait, signal} = {}) {
    requirePluginDirectory(directory);
    let stopped = false, wake, builds = 0, failures = 0;
    const generated = new Set();
    const stop = () => {stopped = true; wake?.();};
    signal?.addEventListener('abort', stop, {once: true});
    if (signal?.aborted) stopped = true;
    signals.once('SIGINT', stop); signals.once('SIGTERM', stop);
    const pause = wait || (() => new Promise(resolve => {
        const timer = setTimeout(() => {wake = undefined; resolve();}, pollInterval);
        wake = () => {clearTimeout(timer); wake = undefined; resolve();};
    }));
    const build = async () => {
        try {
            const result = await deploy(directory);
            if (result.entryPoint) generated.add(result.entryPoint.replace(/\\/g, '/'));
            builds++;
            output.log(`Deployed ${result.name}${result.metadata?.version ? ` ${result.metadata.version}` : ''}. Watching for changes…`);
        } catch (error) {
            failures++;
            output.error(`Build/deploy failed: ${error.message || String(error)}\nThe running plugin was not refreshed. Fix the workspace to retry.`);
        }
    };
    try {
        output.log(`Watching ${directory}. Press Ctrl+C to stop.`);
        let observed;
        try {observed = await snapshot(directory, generated);} catch (error) {output.error(`Workspace scan failed: ${error.message}`);}
        if (!stopped) await build();
        let changedAt, pending = false, scanFailed = false;
        while (!stopped) {
            await pause();
            if (stopped) break;
            let current;
            try {current = await snapshot(directory, generated); scanFailed = false;}
            catch (error) {
                if (!scanFailed) output.error(`Workspace scan failed: ${error.message}`);
                scanFailed = true; continue;
            }
            if (stopped) break;
            if (current !== observed) {observed = current; pending = true; changedAt = now();}
            if (pending && now() - changedAt >= debounceMs) {
                pending = false;
                await build();
            }
        }
        output.log('Stopped watching.');
        return {builds, failures};
    } finally {
        signal?.removeEventListener('abort', stop);
        signals.removeListener('SIGINT', stop); signals.removeListener('SIGTERM', stop);
        wake?.();
    }
}
