import "reflect-metadata";
import {BasicConstraintsExtension, KeyUsagesExtension, KeyUsageFlags, X509CertificateGenerator, X509Certificate as ParsedCertificate} from "@peculiar/x509";
import {verifyCertificateChain} from "./certificateChain";
import {certificateStorage} from "../persistence/certificateStorage";
import * as os from "node:os";
import crypto from 'crypto';
import fs from "node:fs";
import path from "node:path";
import ignore from "ignore";
import {NotificationCenter} from "../desktop/NotificationCenter";
import {safeReadFileSync} from "../filesystem/safeReadFileSync";

export const Certs = {
    EXPIRY_THRESHOLD_DAYS: 90,
    generateDefaultFdoIgnore() {
        return [
            "# .fdoignore autogenerated by FDO",
            "*.log",
            "*.tmp",
            "*.cache",
            "*.bak",
            ".store.json",
            ".*-audit.json",
        ].join(this.LINE_END()) + this.LINE_END();
    },
    IS_WIN() {
        return typeof process !== 'undefined' && process.platform === 'win32'
    },
    LINE_END() {
        return this.IS_WIN() ? '\r\n' : '\n'
    },

    daysUntilExpiry(certPem) {
        const cert = new crypto.X509Certificate(certPem);
        const notAfter = new Date(cert.validTo);
        return (notAfter - new Date()) / (1000 * 60 * 60 * 24);
    },

    async generateRootCA(label = 'root', update = false, {notify = true, onlyIfMissing = false} = {}) {
        if (onlyIfMissing && certificateStorage.list('root').some(cert => cert.label === label)) return false;

        const algorithm = {
            name: "RSASSA-PKCS1-v1_5", hash: "SHA-256",
            publicExponent: new Uint8Array([1, 0, 1]), modulusLength: 4096,
        };
        const keys = await crypto.webcrypto.subtle.generateKey(algorithm, true, ["sign", "verify"]);
        const notBefore = new Date();
        const notAfter = new Date(notBefore);
        notAfter.setFullYear(notBefore.getFullYear() + 1);
        const cert = await X509CertificateGenerator.createSelfSigned({
            serialNumber: crypto.randomBytes(16).toString("hex"),
            name: "CN=FDO Root CA, O=FDO",
            notBefore, notAfter, keys, signingAlgorithm: algorithm,
            extensions: [
                new BasicConstraintsExtension(true, undefined, true),
                new KeyUsagesExtension(KeyUsageFlags.keyCertSign | KeyUsageFlags.digitalSignature, true),
            ],
        }, crypto.webcrypto);
        const certPem = cert.toString("pem");
        const exportedKey = await crypto.webcrypto.subtle.exportKey("pkcs8", keys.privateKey);
        const keyPem = crypto.createPrivateKey({key: Buffer.from(exportedKey), format: "der", type: "pkcs8"})
            .export({format: "pem", type: "pkcs1"});

        // Calculate SHA256 fingerprint of cert PEM
        const sha256 = crypto.createHash('sha256').update(certPem).digest('base64');
        const id = `SHA256://${sha256}`;

        // Get system identity
        const user = os.userInfo().username;
        const host = os.hostname();
        const identity = `${user}@${host}`;

        const now = new Date();

        const previous = update ? certificateStorage.list('root').find(root => root.label === label) : null;
        if (update && !previous) throw new Error('Certificate to renew was not found');
        const entry = {
            ...previous, key: keyPem, cert: certPem, id, identity, label,
            createdAt: now.toISOString(), expiresAt: notAfter.toISOString(),
            lastUsedAt: now.toISOString(), imported: false,
        };
        if (onlyIfMissing) {
            if (!certificateStorage.putIfLabelMissing(entry, 'root')) return false;
        } else certificateStorage.put(entry, 'root', previous?.id);

        if (notify) NotificationCenter.addNotification({source: 'security',
            title: update ? `Signing certificate “${label}” renewed` : `Signing certificate “${label}” created`,
            message: update ? 'The signing identity was replaced. Re-sign plugins that used the previous certificate before starting them again.' : 'The certificate and its encrypted private key are saved. You can now use it to sign plugins.',
            details: `Identity: ${identity}\nFingerprint: ${id}\nExpires: ${notAfter.toISOString()}`,
            type: update ? 'warning' : 'success', actions: [{kind: 'view-settings', tab: 'certificates'}]});
        return true;
    },

    setLabel(id, newName) {
        certificateStorage.update(id, {label: newName});
    },

    export(id) {
        const roots = certificateStorage.list('root');
        const root = roots.find((root) => root.id === id);
        if (root) {
            return {
                cert: root.cert,
            };
        }
        return null;
    },

    async import(file) {
        try {
            const filePath = path.resolve(file);
            const pem = fs.readFileSync(filePath, "utf-8");

            // Split PEM into blocks (certs and private key)
            const pemBlocks = pem
                .split(/(?=-----BEGIN (?:CERTIFICATE|.*PRIVATE KEY)-----)/g)
                .map(block => block.trim())
                .filter(block => block.length > 0);

            const certs = [];
            let privateKeyPem = null;

            for (const block of pemBlocks) {
                if (block.includes("CERTIFICATE")) {
                    try {
                        certs.push({
                            pem: block,
                            cert: new crypto.X509Certificate(block)
                        });
                    } catch {
                        return { success: false, error: "Invalid certificate block" };
                    }
                } else if (block.includes("PRIVATE KEY")) {
                    privateKeyPem = block;
                }
            }

            if (certs.length === 0) {
                return { success: false, error: "No valid certificates found" };
            }

            const now = new Date();
            const leaf = certs[0];
            if (new Date(leaf.cert.validTo) <= now) {
                return { success: false, error: "Certificate is expired" };
            }

            // Validate private key matches public key in leaf cert (if provided)
            let privateKey = null;
            let keyMatches = false;

            if (privateKeyPem) {
                try {
                    privateKey = crypto.createPrivateKey(privateKeyPem);
                    keyMatches = leaf.cert.checkPrivateKey(privateKey);

                    if (!keyMatches) {
                        return { success: false, error: "Private key does not match certificate" };
                    }
                } catch (err) {
                    return { success: false, error: "Invalid private key format: " + err.message };
                }
            }

            // Save to store
            const sha256 = crypto.createHash("sha256").update(leaf.pem).digest("base64");
            const id = `SHA256://${sha256}`;
            const roots = certificateStorage.list('root');

            if (roots.find(root => root.id === id)) {
                return { success: false, error: "Certificate already exists" };
            }

            const entry = {
                cert: leaf.pem,
                id,
                label: `Imported-${(Math.random() + 1).toString(36).substring(2)}`,
                createdAt: now.toISOString(),
                expiresAt: new Date(leaf.cert.validTo).toISOString(),
                lastUsedAt: now.toISOString(),
                imported: true
            };

            if (certs.length > 1) {
                entry.chain = certs.map(c => c.pem);
            }

            if (keyMatches && privateKeyPem) {
                entry.key = privateKeyPem;
            }

            certificateStorage.put(entry);
            NotificationCenter.addNotification({source: 'security', title: 'Certificate imported', type: 'success',
                message: keyMatches ? 'The certificate and matching private key were saved. It can be used for plugin verification and signing.' : 'The certificate was added as a trusted signer. It can verify plugins but has no private key for signing.',
                details: `Label: ${entry.label}\nSubject: ${leaf.cert.subject}\nFingerprint: ${id}`,
                actions: [{kind: 'view-settings', tab: 'certificates'}]});
            return { success: true };
        } catch (err) {
            return { success: false, error: "Failed to import certificate: " + err.message };
        }
    },

    loadIgnorePatterns(pluginDir) {
        const ignoreFile = path.join(pluginDir, ".fdoignore");
        if (!fs.existsSync(ignoreFile)) return null;

        const content = fs.readFileSync(ignoreFile, "utf-8");
        const ig = ignore();
        ig.add(content.split(/\r?\n/).filter(Boolean));
        return ig;
    },

    hashPluginDir(pluginDir) {
        const hash = crypto.createHash("sha256");
        const ig = this.loadIgnorePatterns(pluginDir);

        const walk = (dir) => {
            fs.readdirSync(dir).forEach((file) => {
                const fullPath = path.join(dir, file);
                const relPath = path.relative(pluginDir, fullPath);

                // Always ignore meta + sig files
                if (["fdo.meta.json", "fdo.signature", ".fdoignore"].includes(file)) return;
                // Skip ignored files
                if (ig && ig.ignores(relPath)) return;

                const stat = fs.statSync(fullPath);
                if (stat.isDirectory()) {
                    walk(fullPath);
                } else {
                    const content = fs.readFileSync(fullPath);
                    hash.update(content);
                }
            });
        };

        walk(pluginDir);
        return hash.digest();
    },

    ensureFdoIgnore(pluginDir) {
        const ignorePath = path.join(pluginDir, ".fdoignore");

        if (fs.existsSync(ignorePath)) {
            const content = fs.readFileSync(ignorePath, "utf-8");
            const isAutoGenerated = content.startsWith("# .fdoignore autogenerated by FDO");

            if (!isAutoGenerated) {
                return;
            }
        }

        const content = this.generateDefaultFdoIgnore();
        fs.writeFileSync(ignorePath, content, "utf-8");
    },


    signPlugin(pluginDir, signerLabel) {
        const roots = certificateStorage.list('root');
        const certEntry = roots.find(cert => cert.label === signerLabel);

        if (!certEntry?.hasPrivateKey) {
            return {success: false, error: `Signing certificate “${signerLabel}” is missing. Create one in Settings → Certificates first. FDO encrypts signing keys with macOS Keychain, which may request access when you create or use the key.`}
        }

        this.ensureFdoIgnore(pluginDir);

        const certObj = new crypto.X509Certificate(certEntry.cert);
        const now = new Date();
        if (new Date(certObj.validFrom) > now) {
            return {success: false, error: `Certificate not valid before ${new Date(certObj.validFrom).toISOString()}`};
        }
        if (new Date(certObj.validTo) <= now) {
            return {success: false, error: `Certificate expired on ${new Date(certObj.validTo).toISOString()}`};
        }

        const privateKey = crypto.createPrivateKey(certificateStorage.privateKey(certEntry.id));
        if (privateKey.asymmetricKeyType !== "rsa") {
            return {success: false, error: "Plugin signing requires an RSA private key"};
        }
        const hash = this.hashPluginDir(pluginDir);
        // Preserve the existing format: RSA/SHA-256 over the directory's SHA-256 digest.
        const signature = crypto.sign("sha256", hash, {
            key: privateKey, padding: crypto.constants.RSA_PKCS1_PADDING,
        });

        const normalizedCert = certEntry.cert.trim().replace(/\r\n/g, '\n');
        const fingerprint = crypto.createHash("sha256").update(normalizedCert).digest("base64");

        // 🔍 Check if the certificate is a CA
        const isRoot = certObj.ca;

        const metaInformation = {
            fingerprint: {
                algo: "SHA256",
                value: fingerprint
            },
            label: certEntry.label,
            identity: certEntry.identity,
            signedAt: new Date().toISOString(),
            signatureEncoding: "base64",
            hashAlgorithm: "sha256",
            signatureAlgorithm: "RSASSA-PKCS1-v1_5",
            signedBy: isRoot ? "root" : "developer",
        }

        if (!isRoot) {
            metaInformation.developerCert = certEntry.chain?.length > 1
                ? { chain: [certEntry.cert, ...certEntry.chain.slice(1)] }
                : { cert: certEntry.cert };
        }

        fs.writeFileSync(path.join(pluginDir, "fdo.signature"), signature);
        fs.writeFileSync(
            path.join(pluginDir, "fdo.meta.json"),
            JSON.stringify(metaInformation, null, 2) + this.LINE_END()
        );

        return {success: true}
    },

    verifyPluginSignature(pluginDir, signature, certPem, meta) {
        const {
            signatureEncoding = "base64",
            hashAlgorithm = "sha256",
            signatureAlgorithm = "RSASSA-PKCS1-v1_5"
        } = meta;

        if (signatureAlgorithm !== "RSASSA-PKCS1-v1_5") {
            return {success: false, error: `Unsupported signature algorithm: ${signatureAlgorithm}`};
        }

        try {
            // 1. Hash the plugin content
            const pluginHash = this.hashPluginDir(pluginDir);
            if (!["sha1", "sha256", "sha384", "sha512"].includes(hashAlgorithm)) {
                return {success: false, error: `Unsupported hash algorithm: ${hashAlgorithm}`};
            }

            // 2. Parse cert and validate validity
            const certObj = new crypto.X509Certificate(certPem);
            const now = new Date();
            if (new Date(certObj.validFrom) > now) {
                return {
                    success: false,
                    error: `Certificate not valid before ${new Date(certObj.validFrom).toISOString()}`
                };
            }
            if (new Date(certObj.validTo) <= now) {
                return {success: false, error: `Certificate expired on ${new Date(certObj.validTo).toISOString()}`};
            }

            if (certObj.publicKey.asymmetricKeyType !== "rsa") {
                return {success: false, error: "Plugin signatures require an RSA certificate"};
            }
            const signatureBuffer = Buffer.isBuffer(signature)
                ? signature : Buffer.from(signature, signatureEncoding);
            const isValid = crypto.verify(hashAlgorithm, pluginHash, {
                key: certObj.publicKey, padding: crypto.constants.RSA_PKCS1_PADDING,
            }, signatureBuffer);
            return isValid ? {success: true, cert: certObj} : {success: false, error: "Signature is invalid."};
        } catch (err) {
            return {success: false, error: `Verification of signature failed: ${err.message}`};
        }
    },

    async verifyPlugin(pluginDir) {
        try {
            const metaPath = path.join(pluginDir, "fdo.meta.json");
            const sigPath = path.join(pluginDir, "fdo.signature");

            if (!fs.existsSync(metaPath) || !fs.existsSync(sigPath)) {
                return {success: false, error: "Missing signature or metadata file."};
            }

            const meta = JSON.parse(await safeReadFileSync(metaPath, "utf-8"));
            const signatureBuffer = await safeReadFileSync(sigPath);

            if (
                typeof meta.fingerprint?.value !== "string" ||
                meta.fingerprint.algo?.toLowerCase() !== "sha256"
            ) {
                return {
                    success: false,
                    error: "Invalid or unsupported fingerprint format in metadata.",
                };
            }

            const allCerts = certificateStorage.list();

            let matchedCert;
            let certificateToVerifyAgainst;

            if (meta.signedBy === "developer") {
                if (!meta.developerCert) {
                    return {success: false, error: "Missing developer certificate in meta."};
                }

                const rawChain = meta.developerCert.chain || [meta.developerCert.cert];
                if (!Array.isArray(rawChain) || rawChain.length === 0) {
                    return {success: false, error: "Developer certificate chain is missing or invalid."};
                }

                let certChain;
                try {
                    certChain = rawChain.map(pem => new crypto.X509Certificate(pem));
                } catch (e) {
                    return {success: false, error: `Failed to parse developer certificate chain: ${e.message}`};
                }

                try {
                    const trustedRoot = verifyCertificateChain(certChain, allCerts.map(entry => entry.cert));
                    matchedCert = allCerts.find(entry =>
                        new crypto.X509Certificate(entry.cert).fingerprint256 === trustedRoot.fingerprint256);
                } catch (e) {
                    return {
                        success: false,
                        error: `Developer certificate chain verification failed: ${e.message}`
                    };
                }

                certificateToVerifyAgainst = rawChain[0]
            } else {
                matchedCert = allCerts.find((cert) => {
                    const normalizedCert = cert.cert.trim().replace(/\r\n/g, '\n');
                    const fingerprint = crypto
                        .createHash("sha256")
                        .update(normalizedCert)
                        .digest("base64");
                    return fingerprint === meta.fingerprint.value;
                });

                if (!matchedCert || !matchedCert?.cert) {
                    return {success: false, error: "Signer certificate not found."};
                }

                certificateToVerifyAgainst = matchedCert.cert
            }

            const verifySig = this.verifyPluginSignature(pluginDir, signatureBuffer, certificateToVerifyAgainst, meta);
            if (!verifySig.success) {
                return verifySig;
            }

            certificateStorage.update(matchedCert.id, {lastUsedAt: new Date().toISOString()}, matchedCert.scope);

            return {
                success: true,
                commonName: {name: 'commonName', value: new ParsedCertificate(verifySig.cert.raw).subjectName.getField('CN')[0]},
                signer: matchedCert,
            };
        } catch (err) {
            return {
                success: false,
                error: `Verification failed: ${err.message}`,
            };
        }
    },
}
