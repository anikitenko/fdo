/** @jest-environment node */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {EventEmitter} from 'node:events';
import {snapshotPluginWorkspace, watchPluginDirectory} from '../../src/utils/system/cliDev';

let root;
beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'fdo-cli-dev-'));
    fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({name: 'fixture', main: 'dist/index.cjs'}));
    fs.writeFileSync(path.join(root, 'index.ts'), 'original');
});
afterEach(() => fs.rmSync(root, {recursive: true, force: true}));
test('snapshots ignore generated files and dependencies but detect nested source changes and atomic saves', async () => {
    const original = await snapshotPluginWorkspace(root);
    for (const dir of ['dist', 'node_modules', '.git']) {
        fs.mkdirSync(path.join(root, dir)); fs.writeFileSync(path.join(root, dir, 'file.js'), 'generated');
    }
    fs.writeFileSync(path.join(root, 'fdo.signature'), 'signature');fs.writeFileSync(path.join(root, 'fdo.meta.json'), '{}');
    fs.writeFileSync(path.join(root, '.fdoignore'), '# .fdoignore autogenerated by FDO\n*.log\n');
    expect(await snapshotPluginWorkspace(root)).toBe(original);
    fs.writeFileSync(path.join(root, 'save.tmp'), 'updated');fs.renameSync(path.join(root, 'save.tmp'), path.join(root, 'index.ts'));
    expect(await snapshotPluginWorkspace(root)).not.toBe(original);
    const changed = await snapshotPluginWorkspace(root);
    fs.mkdirSync(path.join(root, 'nested'));fs.writeFileSync(path.join(root, 'nested', 'source.ts'), 'new');
    expect(await snapshotPluginWorkspace(root)).not.toBe(changed);
});
test('manifest changes are watched even when ignored', async () => {
    fs.writeFileSync(path.join(root, '.fdoignore'), 'package.json\n');
    const before = await snapshotPluginWorkspace(root);
    fs.writeFileSync(path.join(root, 'package.json'), '{broken');
    expect(await snapshotPluginWorkspace(root)).not.toBe(before);
});
test('watch serializes deployments, recovers after failures and does not lose edits during a build', async () => {
    const signals = new EventEmitter(), output = {log: jest.fn(), error: jest.fn()};
    let revision = 'one', tick = 0, clock = 0, active = 0, peak = 0;
    const deploy = jest.fn(async () => {
        active++;peak = Math.max(active, peak);
        try {
            if (deploy.mock.calls.length === 1) revision = 'two'; // Edit during initial build.
            if (deploy.mock.calls.length === 2) {revision = 'three'; throw new Error('syntax error');}
            return {name: 'fixture', entryPoint: 'dist/index.cjs'};
        } finally {active--;}
    });
    const result = await watchPluginDirectory(root, {signals, output, deploy, snapshot: async () => revision, now: () => clock, debounceMs: 100,
        wait: async () => {clock += 50;if (++tick === 10) signals.emit('SIGINT');}});
    expect(result).toEqual({builds: 2, failures: 1});expect(peak).toBe(1);expect(deploy).toHaveBeenCalledTimes(3);
    expect(output.error).toHaveBeenCalledWith(expect.stringContaining('syntax error'));
    expect(signals.listenerCount('SIGINT')).toBe(0);expect(signals.listenerCount('SIGTERM')).toBe(0);
});
test('rapid edits are debounced and termination waits for an in-flight deployment', async () => {
    const signals = new EventEmitter();let revision = 0, clock = 0;
    const deploy = jest.fn(async () => {if (deploy.mock.calls.length === 2) signals.emit('SIGTERM');return {name: 'fixture'};});
    expect(await watchPluginDirectory(root, {signals, output: {log: jest.fn(), error: jest.fn()}, deploy, snapshot: async () => String(revision), now: () => clock,
        debounceMs: 100, wait: async () => {clock += 50;if (revision < 3) revision++;}})).toEqual({builds: 2, failures: 0});
    expect(deploy).toHaveBeenCalledTimes(2);expect(signals.listenerCount('SIGTERM')).toBe(0);
});
test('scan errors recover without ending the session', async () => {
    const signals = new EventEmitter();let tick = 0;
    const deploy = jest.fn(async () => ({name: 'fixture'}));
    const snapshot = jest.fn(async () => {if (tick === 1) throw new Error('temporary rename');return String(tick > 1);});
    const output = {log: jest.fn(), error: jest.fn()};
    await watchPluginDirectory(root, {signals, output, deploy, snapshot, debounceMs: 0, wait: async () => {if (++tick === 3) signals.emit('SIGINT');}});
    expect(deploy).toHaveBeenCalledTimes(2);expect(output.error).toHaveBeenCalledWith('Workspace scan failed: temporary rename');
});
test('Electron quit cancellation waits for a deployment and an already-aborted session starts no build', async () => {
    const controller = new AbortController(), signals = new EventEmitter(), output = {log: jest.fn(), error: jest.fn()};
    const deploy = jest.fn(async () => {controller.abort(); await Promise.resolve(); return {name: 'fixture'};});
    expect(await watchPluginDirectory(root, {signals, output, deploy, signal: controller.signal, snapshot: async () => 'same'})).toEqual({builds: 1, failures: 0});
    expect(output.log).toHaveBeenLastCalledWith('Stopped watching.');
    deploy.mockClear();
    expect(await watchPluginDirectory(root, {signals, output, deploy, signal: controller.signal, snapshot: async () => 'same'})).toEqual({builds: 0, failures: 0});
    expect(deploy).not.toHaveBeenCalled();
});
