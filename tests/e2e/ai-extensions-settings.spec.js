const {test, expect, _electron: electron} = require('@playwright/test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {launchElectronApp, closeElectronApp} = require('./helpers/electronApp');

test('Codex skill import uses native Settings IPC, fits the nested tabs, and persists across restart', async ({}, testInfo) => {
    test.setTimeout(90000);
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fdo-ai-extensions-'));
    const file = path.join(directory, 'SKILL.md');
    const content = '---\nname: team-review\ndescription: Shared team review conventions\n---\nPrefer clear names and test observable behavior.\n';
    fs.writeFileSync(file, content);
    let app;
    const launch = async () => {
        app = await launchElectronApp(electron, {isolatedUserDataDir: true, env: {FDO_E2E_USER_DATA_DIR: directory, FDO_E2E_LIVE_AI: '0'}});
        const page = await app.firstWindow();
        page.on('pageerror', error => console.error('AI Extensions renderer error:', error.message));
        await expect.poll(() => page.evaluate(() => typeof window.electron?.settings?.ai?.getExtensions)).toBe('function');
        await page.waitForFunction(() => document.getElementById('root')?.children.length > 0);
        return page;
    };
    try {
        let page = await launch();
        await app.evaluate(({dialog}, file) => {dialog.showOpenDialog = async () => ({canceled: false, filePaths: [file]});}, file);
        await page.getByLabel('Open command search').click();
        await page.getByRole('menuitem').filter({hasText: 'Configure FDO'}).click();
        await page.getByRole('tab', {name: 'AI Extensions', exact: true}).click();
        await expect(page.getByRole('heading', {name: 'AI Extensions'})).toBeVisible();
        for (const name of ['Codex', 'Skills']) {
            const height = await page.getByRole('tab', {name, exact: true}).evaluate(tab => tab.parentElement.getBoundingClientRect().height);
            expect(height).toBeLessThan(60);
        }
        await page.getByRole('button', {name: 'Import SKILL.md'}).click();
        await expect(page.getByLabel('Enable team-review')).toBeVisible();
        await page.getByText('Enable team-review', {exact: true}).click();
        await expect(page.getByLabel('Enable team-review')).not.toBeChecked();
        await page.getByRole('button', {name: 'Save assignments'}).click();
        await expect(page.getByText('Assignments saved. They take effect on the next request.')).toBeVisible();
        const saved = await page.evaluate(() => window.electron.settings.ai.getExtensions());
        expect(saved.skills[0]).toMatchObject({name: 'team-review', content, enabled: false, assistantIds: []});
        await app.evaluate(() => {
            const originalFetch = globalThis.fetch;
            globalThis.fetch = async (url, options) => {
                if (url !== 'https://docs.example.com/mcp') return originalFetch(url, options);
                const message = options.body ? JSON.parse(options.body) : {};
                if (message.method === 'notifications/initialized' || options.method === 'DELETE') return new Response(null, {status: 202});
                const result = message.method === 'initialize'
                    ? {protocolVersion: '2025-06-18', capabilities: {tools: {}}, serverInfo: {name: 'Fixture', version: '1.0.0'}}
                    : {tools: [{name: 'search_docs', description: 'Search documentation', inputSchema: {type: 'object'}}]};
                return new Response(JSON.stringify({jsonrpc: '2.0', id: message.id, result}), {headers: {'content-type': 'application/json'}});
            };
        });
        await page.getByRole('tab', {name: 'MCP Tools', exact: true}).click();
        const addSummary = page.locator('summary').filter({hasText:'Add MCP server'});
        await expect(addSummary).toHaveCSS('cursor','pointer');
        const selectGeometry = await page.getByLabel('Transport', {exact:true}).evaluate(select => {
            const bounds=select.getBoundingClientRect(), icon=select.parentElement.querySelector('svg').getBoundingClientRect();
            return {right:bounds.right-icon.right, center:Math.abs((bounds.top+bounds.bottom-icon.top-icon.bottom)/2)};
        });
        expect(selectGeometry.right).toBeGreaterThanOrEqual(8);expect(selectGeometry.right).toBeLessThanOrEqual(16);
        expect(selectGeometry.center).toBeLessThan(1);
        await page.getByLabel('Server name', {exact: true}).fill('Fixture Docs');
        await page.getByLabel('MCP endpoint', {exact: true}).fill('https://docs.example.com/mcp');
        await page.getByLabel('Bearer token (optional)', {exact: true}).fill('fixture-token');
        await page.getByRole('button',{name:'Add header',exact:true}).click();
        await page.getByLabel('Header name 1',{exact:true}).fill('X-Team');
        await page.getByLabel('Header value 1',{exact:true}).fill('devops');
        await expect(page.getByLabel('Header value 1',{exact:true})).toHaveAttribute('type','password');
        const headerNameBox=await page.getByLabel('Header name 1',{exact:true}).boundingBox();
        const headerValueBox=await page.getByLabel('Header value 1',{exact:true}).boundingBox();
        expect(headerValueBox.x-headerNameBox.x-headerNameBox.width).toBeGreaterThanOrEqual(4);
        await page.screenshot({path:testInfo.outputPath('mcp-header-fields.png')});
        await page.getByRole('button', {name: 'Test and add server', exact: true}).click();
        await expect(page.getByText('MCP connection succeeded.', {exact: false})).toBeVisible();
        const detailsToggle = page.getByRole('button',{name:'Tools and settings for Fixture Docs'});
        await expect(detailsToggle).toHaveAttribute('aria-expanded','false');
        await expect(page.getByLabel('Enable Fixture Docs')).toBeVisible();
        await expect(page.getByText('Allowed tools',{exact:true})).not.toBeVisible();
        await detailsToggle.click();
        await expect(page.getByText('Allowed tools',{exact:true})).toBeVisible();
        await detailsToggle.click();
        await addSummary.focus();await page.keyboard.press('Enter');
        await expect(page.getByLabel('Server name',{exact:true})).toBeVisible();
        await page.keyboard.press('Enter');
        await expect(page.getByLabel('Server name',{exact:true})).not.toBeVisible();
        const savedMcp = (await page.evaluate(() => window.electron.settings.ai.getExtensions())).mcpServers;
        expect(savedMcp[0]).toMatchObject({name: 'Fixture Docs', enabled: false, enabledTools: [], hasBearerToken: true});
        expect(JSON.stringify(savedMcp)).not.toContain('fixture-token');
        await expect(page.getByLabel('Bearer token (optional)', {exact: true})).toHaveValue('');
        const commandFile = path.join(directory, 'stdio fixture.cjs');
        fs.writeFileSync(commandFile, `require('node:readline').createInterface({input:process.stdin}).on('line',line=>{const m=JSON.parse(line);if(m.id===undefined)return;const result=m.method==='initialize'?{protocolVersion:m.params.protocolVersion,capabilities:{tools:{}},serverInfo:{name:'Fixture',version:'1.0.0'}}:{tools:[{name:'local_tool',description:process.env.TEST_MCP==='configured'?'Environment configured':'Missing environment',inputSchema:{type:'object'}}]};process.stdout.write(JSON.stringify({jsonrpc:'2.0',id:m.id,result})+'\\n');});`);
        await addSummary.click();
        await page.getByLabel('Transport',{exact:true}).selectOption('stdio');
        await page.getByLabel('Server name',{exact:true}).fill('Local Fixture');
        await page.getByLabel('Installed command or executable path',{exact:true}).fill(process.execPath);
        await page.getByRole('button',{name:'Add argument',exact:true}).click();
        await page.getByLabel('Argument 1',{exact:true}).fill(commandFile);
        await page.getByLabel('Working directory (optional)',{exact:true}).fill(directory);
        await page.getByRole('button',{name:'Add environment variable',exact:true}).click();
        await page.getByLabel('Environment variable name 1',{exact:true}).fill('TEST_MCP');
        await page.getByLabel('Environment variable value 1',{exact:true}).fill('configured');
        await page.screenshot({path:testInfo.outputPath('mcp-command-fields.png')});
        await page.getByRole('button',{name:'Test and add server',exact:true}).click();
        await expect.poll(async()=> (await page.evaluate(()=>window.electron.settings.ai.getExtensions())).mcpServers.length).toBe(2);
        const commandInventory = await page.evaluate(()=>window.electron.settings.ai.getExtensions());
        const local = commandInventory.mcpServers.find(server=>server.name==='Local Fixture');
        expect(local.tools).toEqual([{name:'local_tool',description:'Environment configured'}]);
        expect(local.environmentKeys).toEqual(['TEST_MCP']);expect(local.environment).toBeUndefined();
        savedMcp.push(local);
        await page.screenshot({path: testInfo.outputPath('ai-mcp-tools.png')});
        await page.screenshot({path: testInfo.outputPath('ai-extensions.png')});
        await page.getByRole('tab',{name:'Hooks',exact:true}).click();
        await page.getByLabel('Hook name',{exact:true}).fill('Team context');
        const hookFile=path.join(directory,'hook fixture with spaces.cjs');
        fs.writeFileSync(hookFile, `let input='';process.stdin.on('data',chunk=>input+=chunk);process.stdin.on('end',()=>{const event=JSON.parse(input);process.stdout.write(JSON.stringify({hookSpecificOutput:{hookEventName:event.hook_event_name,additionalContext:'E2E_HOOK_CANARY '+process.env.TEST_HOOK_VALUE}}));});`);
        await page.getByLabel('Installed hook command or executable path',{exact:true}).fill(process.execPath);
        await page.getByRole('button',{name:'Add argument',exact:true}).click();
        await page.getByLabel('Argument 1',{exact:true}).fill(hookFile);
        await page.getByRole('button',{name:'Add environment variable',exact:true}).click();
        await page.getByLabel('Environment variable name 1',{exact:true}).fill('TEST_HOOK_VALUE');
        await page.getByLabel('Environment variable value 1',{exact:true}).fill('private-hook-value');
        await page.getByRole('button',{name:'Add hook',exact:true}).click();
        await expect(page.getByLabel('Enable Team context',{exact:true})).not.toBeChecked();
        await page.getByRole('button',{name:'Hook settings for Team context',exact:true}).click();
        await page.getByRole('button',{name:'Test hook',exact:true}).click();
        await expect(page.getByText('Hook test completed',{exact:true})).toBeVisible();
        await page.getByText('View test output',{exact:true}).click();
        await expect(page.getByText('E2E_HOOK_CANARY',{exact:false})).toContainText('[REDACTED]');
        await expect(page.getByText('E2E_HOOK_CANARY',{exact:false})).not.toContainText('private-hook-value');
        const savedHooks=(await page.evaluate(()=>window.electron.settings.ai.getExtensions())).hooks;
        expect(savedHooks[0]).toMatchObject({name:'Team context',enabled:false,assistantIds:[],event:'UserPromptSubmit'});
        await page.screenshot({path:testInfo.outputPath('ai-codex-hooks.png')});
        await closeElectronApp(app); app = null;
        page = await launch();
        const restored = await page.evaluate(() => window.electron.settings.ai.getExtensions());
        expect(restored.hooks).toEqual(savedHooks);
        await page.evaluate(id=>window.electron.settings.ai.removeCodexHook(id),savedHooks[0].id);
        expect(restored.skills).toEqual(saved.skills);
        expect(restored.mcpServers).toEqual(savedMcp);
        for (const server of savedMcp) await page.evaluate(id => window.electron.settings.ai.removeCodexMcp(id), server.id);
        await page.evaluate(id => window.electron.settings.ai.removeCodexSkill(id), saved.skills[0].id);
        expect((await page.evaluate(() => window.electron.settings.ai.getExtensions())).skills).toEqual([]);
        expect(fs.readFileSync(file, 'utf8')).toBe(content);
    } finally {if (app) await closeElectronApp(app); fs.rmSync(directory, {recursive: true, force: true});}
});
