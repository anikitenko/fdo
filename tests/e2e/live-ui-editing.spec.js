async function chooseCssProperty(visual, query) {
    const picker = visual.getByRole('combobox', {name: 'CSS property', exact: true});
    await picker.fill(query);
    await picker.press('Enter');
    if (/^[a-z-]+$/.test(query)) await expect(picker).toHaveValue(query);
    await expect(visual.getByLabel('CSS value', {exact: true})).toBeFocused();
}

