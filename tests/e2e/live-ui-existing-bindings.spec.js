const {test,expect,_electron:electron}=require('@playwright/test');
const {launchElectronApp,closeElectronApp}=require('./helpers/electronApp');
const fixture=require('../fixtures/live-ui/existing-bindings.cjs');

test('existing imported SDK bindings can be inspected, rewired, disconnected and restored without changing custom markup',async()=>{
    test.setTimeout(120000);
    const app=await launchElectronApp(electron,{isolatedUserDataDir:true});
    try {
        const home=await app.firstWindow(),opening=app.waitForEvent('window');
        await home.evaluate(()=>window.electron.system.openEditorWindow({name:'Binding management',template:'blank'}));
        const editor=await opening;
        await editor.waitForFunction(()=>window.__editorTestApi?.getState().workspaceTreeIds.includes('/index.ts'));
        await editor.waitForFunction(()=>window.__editorTestApi.getState().nodeModulesLoading===false);
        const files=fixture();
        await editor.evaluate(files=>{for(const [file,content] of Object.entries(files))window.__editorTestApi.createFile(file,content);},files);
        const previewOpening=app.waitForEvent('window');
        await editor.getByRole('button',{name:'Live UI editor',exact:true}).click();
        const visual=await previewOpening,frame=visual.frameLocator('iframe[title="Plugin UI preview"]');
        await frame.getByRole('button',{name:'Check availability',exact:true}).click();
        const binding=visual.getByRole('region',{name:'Binding click #refresh',exact:true});
        await expect(binding.getByLabel('Handler',{exact:true})).toHaveValue('command');
        await expect(binding).toContainText('Handler used by 3 bindings');
        await binding.getByText('Handler source',{exact:true}).click();
        await binding.getByRole('button',{name:'Show handler in code',exact:true}).click();
        await expect.poll(()=>editor.evaluate(()=>window.__editorTestApi.getState().activeTabId)).toBe('/features/actions.ts');
        await binding.getByLabel('Handler',{exact:true}).selectOption('alternative');
        await binding.getByText('Listener options',{exact:true}).click();
        await binding.getByText('Prevent default event',{exact:true}).click();
        await binding.getByRole('button',{name:'Preview binding change',exact:true}).click();
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('alternative');
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/features/actions.ts'))).toBe(files['/features/actions.ts']);
        await expect(frame.getByRole('button',{name:'Check availability',exact:true})).toHaveAttribute('data-domain','availability');
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('command');
        await visual.getByRole('button',{name:'Redo',exact:true}).click();
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('alternative');
        await visual.getByRole('button',{name:'Apply to workspace',exact:true}).click();
        await expect(visual.getByRole('status')).toContainText('Applied. Restore point:');
        const updated=await editor.evaluate(()=>window.__editorTestApi.getFileContent('/features/actions.ts'));
        expect(updated).toContain('"preventDefault": true');
        expect(updated).toContain('handler:"alternative"');
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/view.ts'))).toBe(files['/view.ts']);
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/index.ts'))).toBe(files['/index.ts']);
        await frame.getByRole('button',{name:'Check availability',exact:true}).click();
        await visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByRole('button',{name:'Disconnect binding',exact:true}).click();
        await expect(visual.getByText('No statically matched SDK binding is connected to this element.',{exact:true})).toBeVisible();
        await visual.getByLabel('Existing handler',{exact:true}).selectOption('command');
        await visual.getByRole('button',{name:'Preview new binding',exact:true}).click();
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('command');
        await expect(frame.getByRole('button',{name:'Check availability',exact:true})).toBeVisible();
        await visual.screenshot({path:test.info().outputPath('existing-binding-management.png'),animations:'disabled'});
    } finally {await closeElectronApp(app);}
});

test('engineers can edit, rename, create, duplicate and remove SDK handlers through validated drafts',async()=>{
    test.setTimeout(150000);
    const app=await launchElectronApp(electron,{isolatedUserDataDir:true});
    try {
        const home=await app.firstWindow(),opening=app.waitForEvent('window');
        await home.evaluate(()=>window.electron.system.openEditorWindow({name:'Handler management',template:'blank'}));
        const editor=await opening;
        await editor.waitForFunction(()=>window.__editorTestApi?.getState().workspaceTreeIds.includes('/index.ts'));
        await editor.waitForFunction(()=>window.__editorTestApi.getState().nodeModulesLoading===false);
        const files=fixture();
        await editor.evaluate(files=>{for(const [file,content] of Object.entries(files))window.__editorTestApi.createFile(file,content);},files);
        const previewOpening=app.waitForEvent('window');
        await editor.getByRole('button',{name:'Live UI editor',exact:true}).click();
        const visual=await previewOpening,frame=visual.frameLocator('iframe[title="Plugin UI preview"]');
        await frame.getByRole('button',{name:'Check availability',exact:true}).click();
        await visual.getByRole('button',{name:'Manage handler',exact:true}).click();
        await visual.getByRole('button',{name:'Edit handler code',exact:true}).click();
        let modal=visual.getByRole('dialog');
        const code='({element}) => { if (element) element.setAttribute("data-handler-updated", "true"); }';
        await modal.getByLabel('Handler function',{exact:true}).fill(code);
        await expect(modal.getByRole('button',{name:'Preview handler change',exact:true})).toBeDisabled();
        await modal.getByText('Apply this handler change to all its bindings',{exact:true}).click();
        await visual.screenshot({path:test.info().outputPath('shared-handler-editor.png'),animations:'disabled'});
        await modal.getByRole('button',{name:'Preview handler change',exact:true}).click();
        await expect(modal).toBeHidden();
        await expect(frame.getByRole('button',{name:'Check availability',exact:true})).not.toHaveAttribute('data-handler-updated','true');
        await visual.getByRole('button',{name:'Rename handler',exact:true}).click();
        modal=visual.getByRole('dialog');
        await modal.getByLabel('Handler name',{exact:true}).fill('availability');
        await modal.getByText('Apply this handler change to all its bindings',{exact:true}).click();
        await modal.getByRole('button',{name:'Preview handler change',exact:true}).click();
        await expect(modal).toBeHidden();
        await expect(visual.getByLabel('Handler to manage',{exact:true})).toHaveValue('availability');
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('availability');
        await visual.getByRole('button',{name:'Duplicate handler',exact:true}).click();
        modal=visual.getByRole('dialog');
        await expect(modal.getByLabel('Handler name',{exact:true})).toHaveValue('availabilityCopy');
        await modal.getByRole('button',{name:'Preview handler change',exact:true}).click();
        await expect(modal).toBeHidden();
        await expect(visual.getByLabel('Handler to manage',{exact:true})).toHaveValue('availabilityCopy');
        await visual.getByRole('button',{name:'Remove unused handler',exact:true}).click();
        await visual.getByRole('dialog').getByRole('button',{name:'Preview handler change',exact:true}).click();
        await expect(visual.getByRole('dialog')).toBeHidden();
        await visual.getByRole('button',{name:'New click handler',exact:true}).click();
        modal=visual.getByRole('dialog');
        await modal.getByLabel('Handler name',{exact:true}).fill('newClick');
        await modal.getByRole('button',{name:'Preview handler change',exact:true}).click();
        await expect(modal).toBeHidden();
        await expect(visual.getByLabel('Handler to manage',{exact:true})).toHaveValue('newClick');
        await expect(visual.getByRole('region',{name:'Binding click #refresh',exact:true}).getByLabel('Handler',{exact:true})).toHaveValue('availability');
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/features/actions.ts'))).toBe(files['/features/actions.ts']);
        await visual.getByRole('button',{name:'Apply to workspace',exact:true}).click();
        await expect(visual.getByRole('status')).toContainText('Applied. Restore point:');
        const updated=await editor.evaluate(()=>window.__editorTestApi.getFileContent('/features/actions.ts'));
        expect(updated).toContain(code);
        expect(updated.match(/handler:"availability"/g)).toHaveLength(3);
        expect(updated).toContain('"newClick"');
        expect(updated).not.toContain('availabilityCopy');
        expect(updated).toContain(files['/features/actions.ts'].slice(files['/features/actions.ts'].indexOf('  setup:')));
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/view.ts'))).toBe(files['/view.ts']);
        await frame.getByRole('button',{name:'Check availability',exact:true}).click();
        await visual.getByRole('button',{name:'Manage handler',exact:true}).click();
        await visual.screenshot({path:test.info().outputPath('handler-management.png'),animations:'disabled'});
    } finally {await closeElectronApp(app);}
});
