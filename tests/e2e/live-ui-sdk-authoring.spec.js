const {test,expect,_electron:electron}=require('@playwright/test');
const {launchElectronApp,closeElectronApp}=require('./helpers/electronApp');

test('SDK authoring components insert, edit typed properties and simulate states without applying source',async()=>{
    test.setTimeout(180000);
    const app=await launchElectronApp(electron,{isolatedUserDataDir:true});
    try {
        const home=await app.firstWindow(),opening=app.waitForEvent('window');
        await home.evaluate(()=>window.electron.system.openEditorWindow({name:'sdk-authoring-gallery',template:'blank'}));
        const editor=await opening;
        await editor.waitForFunction(()=>window.__editorTestApi?.getState().currentVersion);
        const initial=await editor.evaluate(()=>window.__editorTestApi.getFileContent('/render.tsx'));
        const previewOpening=app.waitForEvent('window');
        await editor.getByRole('button',{name:'Live UI editor',exact:true}).click();
        const visual=await previewOpening,frame=visual.frameLocator('iframe[title="Plugin UI preview"]');
        await visual.getByText('SDK catalog',{exact:true}).click();
        for(const name of ['Progress Bar','Toast','Inline Alert','Toast Region','Async Action Button','Tabs','Disclosure','Accordion']) {
            await visual.getByRole('button',{name:'main',exact:true}).click();
            await visual.getByRole('button',{name:'Add '+name,exact:true}).click();
            await expect(frame.locator('[data-fdo-component="fdo.'+({'Progress Bar':'progress-bar','Toast':'toast','Inline Alert':'inline-alert','Toast Region':'toast-region','Async Action Button':'async-action-button','Tabs':'tabs','Disclosure':'disclosure','Accordion':'accordion'}[name])+'"]').first()).toBeAttached();
        }
        await expect(visual.getByRole('textbox',{name:'Search SDK catalog'})).toHaveAttribute('placeholder','Search SDK…');
        for(const [name,add,label] of [['Tabs','Add tab','Deployment'],['Accordion','Add section','Operations']]) {
            await visual.getByRole('button',{name:'Inspect '+name,exact:true}).click();
            await visual.getByRole('button',{name:add,exact:true}).click();
            await expect(visual.getByLabel('Item label',{exact:true})).toHaveValue(name==='Tabs' ? 'New tab' : 'New section');
            await visual.getByLabel('Item label',{exact:true}).fill(label);
            await visual.getByRole('button',{name:'Preview item label',exact:true}).click();
            await visual.getByRole('button',{name:'Move item up',exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true})).toHaveValue(name==='Tabs' ? 'item-1' : 'item-2');
            await visual.getByRole('button',{name:'Remove item',exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true}).locator('option').filter({hasText:label})).toHaveCount(0);
            await visual.getByRole('button',{name:'Undo',exact:true}).click();
            await expect(visual.getByLabel('Item label',{exact:true})).toHaveValue(label);
            await visual.getByRole('button',{name:'Redo',exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true}).locator('option').filter({hasText:label})).toHaveCount(0);
            await visual.getByRole('button',{name:'Undo',exact:true}).click();
        }
        await visual.getByRole('button',{name:'Inspect Tabs',exact:true}).click();
        await visual.getByLabel('Default tab',{exact:true}).selectOption('advanced');
        await expect(frame.locator('#fdo-tabs [data-fdo-tab="advanced"]')).toHaveAttribute('aria-selected','true');
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(visual.getByLabel('Default tab',{exact:true})).toHaveValue('');
        await expect(frame.locator('#fdo-tabs [data-fdo-tab="general"]')).toHaveAttribute('aria-selected','true');
        await visual.getByRole('button',{name:'Redo',exact:true}).click();
        await expect(visual.getByLabel('Default tab',{exact:true})).toHaveValue('advanced');
        await visual.getByLabel('Default tab',{exact:true}).selectOption('');
        await expect(frame.locator('#fdo-tabs [data-fdo-tab="general"]')).toHaveAttribute('aria-selected','true');
        await visual.getByLabel('Default tab',{exact:true}).selectOption('advanced');
        await expect(frame.locator('#fdo-tabs [data-fdo-tab="advanced"]')).toHaveAttribute('aria-selected','true');
        await visual.getByLabel('Default tab',{exact:true}).scrollIntoViewIfNeeded();
        const defaultScreenshot=test.info().outputPath('default-tab.png');
        await visual.screenshot({path:defaultScreenshot,animations:'disabled'});
        await test.info().attach('Default tab selection',{path:defaultScreenshot,contentType:'image/png'});
        await visual.getByRole('button',{name:'Inspect Accordion',exact:true}).click();
        await visual.getByLabel('Collection item',{exact:true}).selectOption('item-2');
        await visual.getByLabel('Section initially open',{exact:true}).selectOption('true');
        await expect(frame.locator('#fdo-accordion [data-fdo-item="item-2"] details')).toHaveAttribute('open','');
        await expect(frame.locator('#fdo-accordion [data-fdo-item="first"] details')).not.toHaveAttribute('open');
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(frame.locator('#fdo-accordion [data-fdo-item="first"] details')).toHaveAttribute('open','');
        await visual.getByRole('button',{name:'Redo',exact:true}).click();
        await expect(frame.locator('#fdo-accordion [data-fdo-item="item-2"] details')).toHaveAttribute('open','');
        for(const [name,label,id] of [['Tabs','Deployment','#fdo-tabs'],['Accordion','Operations','#fdo-accordion']]) {
            await visual.getByRole('button',{name:'Inspect '+name,exact:true}).click();
            const key=await visual.getByLabel('Collection item',{exact:true}).locator('option').filter({hasText:label}).getAttribute('value');
            await visual.getByLabel('Collection item',{exact:true}).selectOption(key);
            await visual.getByLabel('Add to slot',{exact:true}).selectOption('text');
            await visual.getByRole('button',{name:'Preview slot addition',exact:true}).click();
            await expect(visual.getByRole('button',{name:'Remove item',exact:true})).toBeDisabled();
            await visual.getByLabel('Add to slot',{exact:true}).selectOption('result');
            await visual.getByRole('button',{name:'Preview slot addition',exact:true}).click();
            await visual.getByRole('button',{name:'up pre · Results appear here',exact:true}).click();
            await visual.getByRole('button',{name:'Preview item',exact:true}).click();
            if(name==='Tabs') await expect(visual.getByLabel('Default tab',{exact:true})).toHaveValue('advanced');
            await expect(frame.locator(id).getByText('New text',{exact:true})).toBeVisible();
            await visual.getByRole('button',{name:'Inspect p · New text',exact:true}).click();
            await expect(frame.locator(id).getByText('New text',{exact:true})).toBeVisible();
            await visual.getByLabel('Text',{exact:true}).fill(label+' help <safe>');
            await visual.getByRole('button',{name:'Preview change',exact:true}).click();
            await expect(frame.locator(id).getByText(label+' help <safe>',{exact:true})).toBeVisible();
            await expect(visual.getByText('Return to '+label+' in '+name+'.',{exact:true})).toBeVisible();
            if(name==='Tabs') {
                await visual.getByRole('button',{name:'Edit Tabs content',exact:true}).scrollIntoViewIfNeeded();
                const contextScreenshot=test.info().outputPath('item-navigation-context.png');
                await visual.screenshot({path:contextScreenshot,animations:'disabled'});
                await test.info().attach('Item navigation context',{path:contextScreenshot,contentType:'image/png'});
            }
            await visual.getByRole('button',{name:'Edit '+name+' content',exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true})).toHaveValue(key);
            await visual.getByRole('button',{name:'Preview item',exact:true}).click();
            const body=name==='Tabs' ? frame.locator(id+' [data-fdo-panel="'+key+'"]') : frame.locator(id+' [data-fdo-item="'+key+'"] details');
            await expect(body.locator('[data-fdo-ui-id]')).toHaveText(['Results appear here',label+' help <safe>']);
            const destination=name==='Tabs' ? 'advanced' : 'second',destinationLabel=name==='Tabs' ? 'Advanced · Body' : 'Second section · Body';
            await visual.getByLabel('Move content to',{exact:true}).selectOption('item:'+destination);
            await visual.getByRole('button',{name:'Move p · '+label+' help <safe> to '+destinationLabel,exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true})).toHaveValue(destination);
            await visual.getByRole('button',{name:'Preview item',exact:true}).click();
            const destinationBody=name==='Tabs' ? frame.locator(id+' [data-fdo-panel="'+destination+'"]') : frame.locator(id+' [data-fdo-item="'+destination+'"] details');
            await expect(destinationBody.getByText(label+' help <safe>',{exact:true})).toBeVisible();
            await expect(destinationBody.getByText(label+' help <safe>',{exact:true})).toBeInViewport();
            await expect(destinationBody.locator('[data-fdo-ui-id]')).toHaveText([label+' help <safe>']);
            await expect(body.locator('[data-fdo-ui-id]')).toHaveText(['Results appear here']);
            await visual.getByRole('button',{name:'Undo',exact:true}).click();
            await expect(destinationBody.locator('[data-fdo-ui-id]')).toHaveText([]);
            await expect(body.locator('[data-fdo-ui-id]')).toHaveText(['Results appear here',label+' help <safe>']);
            await visual.getByRole('button',{name:'Redo',exact:true}).click();
            await visual.getByRole('button',{name:'Preview item',exact:true}).click();
            await expect(destinationBody.getByText(label+' help <safe>',{exact:true})).toBeVisible();
            await expect(destinationBody.getByText(label+' help <safe>',{exact:true})).toBeInViewport();
            await visual.getByRole('button',{name:'Inspect p · '+label+' help <safe>',exact:true}).click();
            await visual.getByRole('button',{name:'Edit '+name+' content',exact:true}).click();
            await expect(visual.getByLabel('Collection item',{exact:true})).toHaveValue(destination);

        }
        await visual.getByRole('textbox',{name:'Search SDK catalog'}).scrollIntoViewIfNeeded();
        await visual.getByLabel('Add to slot',{exact:true}).scrollIntoViewIfNeeded();
        const collectionScreenshot=test.info().outputPath('sdk-collection-editor.png');
        await visual.screenshot({path:collectionScreenshot,animations:'disabled'});
        await test.info().attach('SDK collection editor',{path:collectionScreenshot,contentType:'image/png'});
        await visual.getByRole('button',{name:'Inspect Inline Alert · New Inline Alert',exact:true}).click();
        await visual.getByLabel('Component property',{exact:true}).selectOption('variant');
        await visual.getByLabel('Property value',{exact:true}).selectOption('success');
        await visual.getByRole('button',{name:'Preview component property',exact:true}).click();
        await expect(frame.locator('#fdo-inline-alert')).toHaveAttribute('data-fdo-variant','success');
        await visual.getByLabel('Preview state',{exact:true}).selectOption('hidden');
        await expect(frame.locator('#fdo-inline-alert')).toBeHidden();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('authored');
        await expect(frame.locator('#fdo-inline-alert')).toBeVisible();
        await visual.getByRole('button',{name:'Inspect Toast · New Toast',exact:true}).click();
        await expect(frame.locator('#fdo-toast')).toBeHidden();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('open');
        await expect(frame.locator('#fdo-toast')).toBeVisible();
        await visual.getByRole('button',{name:'Add toast progress',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).toBeAttached();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('open');
        await expect(frame.locator('#fdo-toast-progress')).toBeVisible();
        await expect(frame.locator('#fdo-toast-progress')).not.toHaveAttribute('value');
        await visual.getByLabel('Progress label',{exact:true}).fill('Upload <safe>');
        await visual.getByLabel('Progress value',{exact:true}).fill('5');
        await visual.getByLabel('Progress maximum',{exact:true}).fill('10');
        await visual.getByRole('button',{name:'Preview progress settings',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).toHaveAttribute('value','5');
        await expect(frame.locator('#fdo-toast-progress')).toHaveAttribute('max','10');
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).not.toHaveAttribute('value');
        await visual.getByRole('button',{name:'Redo',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).toHaveAttribute('value','5');
        await visual.getByRole('button',{name:'Remove toast progress',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).toHaveCount(0);
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).toHaveAttribute('value','5');
        await visual.getByLabel('Progress value',{exact:true}).fill('');
        await visual.getByRole('button',{name:'Preview progress settings',exact:true}).click();
        await expect(frame.locator('#fdo-toast-progress')).not.toHaveAttribute('value');
        await visual.getByLabel('Progress value',{exact:true}).fill('0');
        await visual.getByRole('button',{name:'Preview progress settings',exact:true}).click();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('open');
        await expect(frame.getByRole('progressbar',{name:'Upload <safe>',exact:true})).toHaveAttribute('value','0');
        await visual.getByRole('button',{name:'Preview progress settings',exact:true}).scrollIntoViewIfNeeded();
        const progressScreenshot=test.info().outputPath('toast-progress-editor.png');
        await visual.screenshot({path:progressScreenshot,animations:'disabled'});
        await test.info().attach('Toast progress editor',{path:progressScreenshot,contentType:'image/png'});

        await visual.getByRole('button',{name:'Inspect Toast Region',exact:true}).click();
        await visual.getByRole('button',{name:'Add toast to region',exact:true}).click();
        await expect(frame.locator('#fdo-toast-region #fdo-toast-2')).toBeAttached();
        await expect(visual.getByLabel('Component property',{exact:true})).toBeVisible();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('open');
        await expect(frame.locator('#fdo-toast-region #fdo-toast-2')).toBeVisible();
        await visual.getByRole('button',{name:'Undo',exact:true}).click();
        await expect(frame.locator('#fdo-toast-region #fdo-toast-2')).toHaveCount(0);
        await visual.getByRole('button',{name:'Redo',exact:true}).click();
        await expect(frame.locator('#fdo-toast-region #fdo-toast-2')).toBeAttached();
        await visual.getByRole('button',{name:'Inspect Toast Region',exact:true}).click();
        await visual.getByRole('button',{name:'Add toast to region',exact:true}).scrollIntoViewIfNeeded();
        const regionScreenshot=test.info().outputPath('toast-region-composition.png');
        await visual.screenshot({path:regionScreenshot,animations:'disabled'});
        await test.info().attach('Toast Region composition',{path:regionScreenshot,contentType:'image/png'});

        await visual.getByRole('button',{name:'Inspect Async Action Button',exact:true}).click();
        await visual.getByLabel('Preview state',{exact:true}).selectOption('pending');
        await expect(frame.locator('#fdo-async-action-button')).toHaveAttribute('aria-busy','true');
        await expect(frame.locator('#fdo-async-action-button [data-fdo-action="run"]')).toBeDisabled();
        const screenshot=test.info().outputPath('sdk-authoring-components.png');
        await visual.screenshot({path:screenshot,animations:'disabled'});
        await test.info().attach('SDK authoring components',{path:screenshot,contentType:'image/png'});
        expect(await editor.evaluate(()=>window.__editorTestApi.getFileContent('/render.tsx'))).toBe(initial);
        await visual.getByRole('button',{name:'Apply to workspace',exact:true}).click();
        await expect(visual.getByRole('status')).toContainText('Applied. Restore point:');
        const files=await editor.evaluate(()=>Object.fromEntries(window.__editorTestApi.getState().workspaceTreeIds.filter(id=>!id.startsWith('/node_modules/')&&!id.startsWith('/dist/')).map(id=>[id,window.__editorTestApi.getFileContent(id)]).filter(([,content])=>typeof content==='string')));
        const build=await home.evaluate(latestContent=>window.electron.plugin.build({latestContent}),files);
        expect(build.success,build.error).toBe(true);
        expect(files['/render.tsx']).not.toContain('Example failure (preview)');
    } finally {await closeElectronApp(app);}
});
